"""A generated Obsidian Bases dashboard over one repository's memory notes.

`graphify-worktree dashboard PATH` writes Projects/<repository>/Memory.base
beside the repository's Memory/ folder in the authored vault (Bases can only
query notes in their own vault). It needs Obsidian consent, never creates the
Memory folder, and never overwrites a copy that differs from what it would
write, so view edits made in Obsidian are kept.
"""

import os
import stat
import uuid

from graphify_worktree.errors import MemoryRequestError
from graphify_worktree.memory import store
from graphify_worktree.memory.service import memory_directory, repository
from graphify_worktree.policy import require, resolve_root


FILENAME = "Memory.base"
TEMPLATE = """\
# Generated by grovekeeper (`graphify-worktree dashboard`). The command never overwrites
# a changed copy: delete this file and run it again to get the current template.
filters:
  and:
    - 'file.inFolder("{folder}")'
    - 'file.ext == "md"'

formulas:
  review: 'if(stale_after && date(stale_after) < today(), "stale", if(verify_by && date(verify_by) < today(), "verify due", ""))'

properties:
  title:
    displayName: "Title"
  kind:
    displayName: "Kind"
  status:
    displayName: "Status"
  branch:
    displayName: "Branch"
  date:
    displayName: "Created"
  recorded_by:
    displayName: "Recorded by"
  superseded_by:
    displayName: "Superseded by"
  formula.review:
    displayName: "Review"

views:
  - type: table
    name: "Current"
    filters:
      and:
        - 'status != "superseded"'
    groupBy:
      property: status
      direction: ASC
    order:
      - title
      - kind
      - branch
      - date
      - verify_by
      - stale_after
      - formula.review
  - type: table
    name: "By kind"
    filters:
      and:
        - 'status != "superseded"'
    groupBy:
      property: kind
      direction: ASC
    order:
      - title
      - status
      - branch
      - date
  - type: table
    name: "Proposals by branch"
    filters:
      and:
        - 'status == "proposed"'
    groupBy:
      property: branch
      direction: ASC
    order:
      - title
      - kind
      - date
      - recorded_by
  - type: table
    name: "Needs review"
    filters:
      and:
        - 'status != "superseded"'
        - 'formula.review != ""'
    order:
      - title
      - formula.review
      - verify_by
      - stale_after
      - status
  - type: table
    name: "History"
    filters:
      and:
        - 'status == "superseded"'
    order:
      - title
      - kind
      - date
      - superseded_by
"""


def render(folder):
    return TEMPLATE.format(folder=folder)


def write(root, *, once=False):
    """Create the dashboard, or report it unchanged; refuse to replace a changed copy."""
    root = resolve_root(root)
    require(root, capability="obsidian", once=once)
    repo = repository(root)
    memory = memory_directory(repo)
    project = memory.parent
    text = render(memory.relative_to(memory.parents[2]).as_posix())
    path = project / FILENAME
    try:
        with store.directory(project, create=True, writing=True) as fd:
            try:
                info = os.stat(FILENAME, dir_fd=fd, follow_symlinks=False)
            except FileNotFoundError:
                info = None
            if info is not None:
                if not stat.S_ISREG(info.st_mode):
                    raise MemoryRequestError(f"{path} must be a regular file, not a symlink")
                descriptor = os.open(FILENAME, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=fd)
                with os.fdopen(descriptor, encoding="utf-8") as stream:
                    if stream.read() != text:
                        raise MemoryRequestError(
                            f"{path} was changed outside grovekeeper; it is kept. Delete it to regenerate.")
                return {"state": "unchanged", "path": str(path)}
            temporary = f".{uuid.uuid4()}.tmp"
            try:
                descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=fd)
                with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
                    stream.write(text)
                os.replace(temporary, FILENAME, src_dir_fd=fd, dst_dir_fd=fd)
            finally:
                try:
                    os.unlink(temporary, dir_fd=fd)
                except FileNotFoundError:
                    pass
    except (OSError, UnicodeError) as error:
        raise MemoryRequestError(f"dashboard storage error: {error}") from error
    return {"state": "created", "path": str(path)}
